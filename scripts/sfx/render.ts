/**
 * Renders the combat sound bank (scripts/sfx/combat.ts) into one sprite file.
 *
 *   npx tsx scripts/sfx/render.ts                 # public/audio/sfx/combat.mp3 + src/audio/combatClips.ts
 *   npx tsx scripts/sfx/render.ts --reel <dir>    # also a listening reel (<dir>/combat-reel.mp3) and a WAV per clip
 *
 * Needs ffmpeg (libmp3lame). The game loads /play/audio/sfx/combat.mp3 once, decodes it and plays
 * slices of it (src/audio/CombatBank.ts). Every clip is mono, levelled to its loudness target,
 * soft-limited to −1 dBFS and separated by silence, so MP3 encoder delay never clips a transient.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Buf, fadeEnd, limit, loudness, mix, peak, Rng, room, SR, tail, wavMono } from './dsp';
import { CLIPS } from './combat';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'public', 'audio', 'sfx');
const GAP = 0.08; // silence around every clip in the sprite
const CEIL = 0.89; // −1 dBFS

const args = process.argv.slice(2);
const reelDir = args.includes('--reel') ? args[args.indexOf('--reel') + 1] : null;

function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

/** Renders one variant: model → room → trim → level → limit. */
export function renderClip(name: string, v: number): Buf {
  const spec = CLIPS.find((c) => c.name === name)!;
  const rng = new Rng(hash(name) + v * 7919 + 1);
  const dry = fadeEnd(spec.make(rng, v));
  let b = tail(room(dry, rng, spec.wet, spec.rt), 0.03);
  const gain = Math.pow(10, (spec.target - loudness(b)) / 20);
  for (let i = 0; i < b.length; i++) b[i] *= gain;
  b = limit(b, CEIL);
  // fade-in guard of 0.5 ms (no DC click)
  for (let i = 0; i < 22 && i < b.length; i++) b[i] *= i / 22;
  return b;
}

const rendered = new Map<string, Buf[]>();
const report: string[] = [];
let total = 0;
for (const c of CLIPS) {
  const vs: Buf[] = [];
  for (let v = 0; v < c.variants; v++) {
    const b = renderClip(c.name, v);
    vs.push(b);
    total += b.length / SR + GAP;
    report.push(`${c.name.padEnd(16)} v${v}  ${(b.length / SR).toFixed(3)} s  peak ${(20 * Math.log10(peak(b))).toFixed(1)} dBFS  loud ${loudness(b).toFixed(1)} dB`);
  }
  rendered.set(c.name, vs);
}

// the sprite: GAP, clip, GAP, clip …
const sprite = new Float64Array(Math.ceil((total + GAP) * SR));
const manifest: Record<string, Array<[number, number]>> = {};
let pos = GAP;
for (const c of CLIPS) {
  manifest[c.name] = [];
  for (const b of rendered.get(c.name)!) {
    mix(sprite, b, pos);
    manifest[c.name].push([+pos.toFixed(4), +(b.length / SR).toFixed(4)]);
    pos += b.length / SR + GAP;
  }
}

mkdirSync(OUT, { recursive: true });
const tmp = join(OUT, 'combat.wav');
writeFileSync(tmp, wavMono(sprite));
const mp3 = join(OUT, 'combat.mp3');
execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', tmp, '-ac', '1', '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', '96k', mp3]);
execFileSync('rm', ['-f', tmp]);

// where the first clip's sound really starts (the game uses it to measure MP3 decoder delay)
let onset = 0;
for (let i = 0; i < sprite.length; i++) if (Math.abs(sprite[i]) > 0.01) { onset = i / SR; break; }

const ts = `// GENERATED by scripts/sfx/render.ts — do not edit by hand (re-render instead).
/** Slices of public/audio/sfx/combat.mp3: clip name → variants as [start s, duration s]. */
export const COMBAT_FILE = 'audio/sfx/combat.mp3';
/** Time (s) of the first sample above 0.01 in the rendered sprite. */
export const COMBAT_ONSET = ${onset.toFixed(5)};
export const COMBAT_CLIPS: Record<string, ReadonlyArray<readonly [number, number]>> = ${JSON.stringify(manifest, null, 0).replace(/\],"/g, '],\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};
`;
writeFileSync(join(ROOT, 'src', 'audio', 'combatClips.ts'), ts);

console.log(report.join('\n'));
console.log(`\n${CLIPS.length} sounds, ${[...rendered.values()].reduce((a, v) => a + v.length, 0)} variants, ${total.toFixed(1)} s, combat.mp3 ${(statSync(mp3).size / 1024).toFixed(0)} KB`);

// ------------------------------------------------------------------ listening reel
if (reelDir) {
  mkdirSync(join(reelDir, 'clips'), { recursive: true });
  for (const [name, vs] of rendered) vs.forEach((b, v) => writeFileSync(join(reelDir, 'clips', `${name}_${v}.wav`), wavMono(b)));
  const one = (name: string, v = 0) => rendered.get(name)![Math.min(v, rendered.get(name)!.length - 1)];
  type Ev = [string, number, number]; // clip, at (s), gain
  const items: Ev[][] = [];
  for (const c of CLIPS) items.push([[c.name, 0, 1]]);
  // a few combinations the way the game layers them
  items.push([['swing_blade', 0, 0.6], ['hit_flesh', 0.17, 1], ['acc_slash', 0.17, 0.7]]);
  items.push([['swing_axe', 0, 0.6], ['hit_armour', 0.22, 1], ['acc_chop', 0.22, 0.7]]);
  items.push([['swing_club', 0, 0.6], ['hit_bone', 0.26, 1], ['acc_crunch', 0.26, 0.7]]);
  items.push([['swing_blade', 0, 0.6], ['hit_scale', 0.17, 1.1], ['acc_slash', 0.17, 0.7], ['crit', 0.17, 0.9]]);
  items.push([['swing_blade', 0, 0.6], ['parry', 0.17, 1]]);
  items.push([['bow', 0, 0.8], ['arrow_fly', 0.02, 0.6], ['arrow_flesh', 0.25, 1]]);
  items.push([['crossbow', 0, 0.8], ['arrow_wood', 0.2, 1]]);
  items.push([['zap_energy', 0, 0.8], ['zaphit_energy', 0.22, 1]]);
  let len = 0.3;
  const placed: Array<[Buf, number, number]> = [];
  for (const group of items) {
    let end = 0;
    for (const [name, at, g] of group) { placed.push([one(name), len + at, g]); end = Math.max(end, at + one(name).length / SR); }
    len += end + 0.32;
  }
  const reel = new Float64Array(Math.ceil((len + 0.3) * SR));
  // as in game (BANK_GAIN 0.35 × master 0.6), plus the same +8 dB make-up as the before reel
  for (const [b, at, g] of placed) mix(reel, b, at, g * 0.35 * 0.6 * 2.5);
  limit(reel, CEIL);
  const wav = join(reelDir, 'combat-reel.wav');
  writeFileSync(wav, wavMono(reel));
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', wav, '-c:a', 'libmp3lame', '-b:a', '160k', join(reelDir, 'combat-reel.mp3')]);
  console.log(`reel ${len.toFixed(1)} s → ${join(reelDir, 'combat-reel.mp3')}`);
}
